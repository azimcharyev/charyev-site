/**
 * Тарифы (Figma, node 365:1192 — раскладка, node 365:1190 — карточки).
 *
 * Пять направлений, три видны одновременно, остальные листаются стрелками.
 * У «Продакшна» и «Контента» внутри есть тарифы-переключатели, у остальных
 * направлений тариф один — тогда ряд пилюль не рисуется.
 *
 * Тексты перенесены из макета дословно.
 */

export type Tier = {
  id: string;
  label: string;
  features: string[];
  price: string;
};

export type Service = {
  id: string;
  title: string;
  defaultTier: string;
  tiers: Tier[];
};

/** Ник Азима в телеграме — из него собирается ссылка кнопки «Выбрать». */
export const TELEGRAM_USERNAME = 'charyev_azim';

/**
 * Ссылка на переписку с заранее набранным сообщением.
 *
 * Параметр ?text= телеграм подставляет в поле ввода: пользователь попадает в
 * чат, текст уже написан, остаётся нажать «отправить». Работает в мобильных
 * приложениях; в веб-версии и на десктопе параметр может игнорироваться —
 * тогда чат просто откроется пустым, без ошибки.
 */
export function getTelegramHref(service: Service, tier: Tier) {
  const name = service.tiers.length > 1 ? `${service.title} — ${tier.label}` : service.title;
  const message = `Здравствуйте Азим! Я выбрал тариф «${name}». Хотел бы обсудить условия сотрудничества.`;

  return `https://t.me/${TELEGRAM_USERNAME}?text=${encodeURIComponent(message)}`;
}

