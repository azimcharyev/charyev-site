/**
 * Общий признак «страницу сейчас прокручивают».
 *
 * Плитка кейса во время прокрутки наклоняется — .cases__grid задаёт
 * perspective, и rotateX по ней настоящий трёхмерный. Всё, что живёт внутри
 * такой плитки, приходится растеризовать заново на каждый кадр наклона, а
 * плитка крупная: 405x716 единиц макета, три в ряд. Это единственное место на
 * сайте, где прокрутка проваливалась до 300 мс на кадр.
 *
 * Внутри плитки два таких жильца:
 *
 *  - видео: под трёхмерным поворотом его нельзя отдать быстрым путём
 *    композитора, кадр за кадром текстура пересобирается с перспективой;
 *  - кольцо «Наведи и посмотри»: у него бесконечная анимация вращения, то есть
 *    слой плитки не успокаивается вообще никогда.
 *
 * Замеры на 1512x860, прокрутка всей страницы (сумма кадров дольше 32 мс):
 * как было — 1675 мс, худший кадр 308 мс; пауза видео — 325 мс и 167 мс;
 * плюс остановка кольца — 67 мс и 67 мс.
 *
 * Поэтому на время прокрутки ролики ставим на паузу, а кольцо останавливаем:
 * застывший слой композитор закэширует и будет только двигать. При быстром
 * пролистывании ни движения в кадре, ни вращения надписи всё равно не
 * разобрать. Прокрутка остановилась — всё возвращается само.
 *
 * Один слушатель на всё приложение, а не по одному на каждого потребителя:
 * слушателей прокрутки на странице и так хватает. Класс на <html> позволяет
 * останавливать чисто оформительские анимации из CSS, без участия React.
 */

const listeners = new Set<() => void>();
const SETTLE_DELAY = 180;

let scrolling = false;
let settleTimer = 0;

function notify() {
  document.documentElement.classList.toggle('is-scrolling', scrolling);
  listeners.forEach((listener) => listener());
}

function onScroll() {
  if (!scrolling) {
    scrolling = true;
    notify();
  }

  clearTimeout(settleTimer);
  settleTimer = window.setTimeout(() => {
    scrolling = false;
    notify();
  }, SETTLE_DELAY);
}

/* Подписка навешивается сразу при загрузке модуля, а не по первому
   подписчику: класс на <html> нужен и там, где ни одного подписчика нет —
   например, во вкладке «Фото», где плитки без видео, но кольцо на них есть. */
if (typeof window !== 'undefined') {
  window.addEventListener('scroll', onScroll, { passive: true });
}

export function isScrolling() {
  return scrolling;
}

export function subscribeScrollActivity(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
